    /// <summary>
    /// Folders that are never staged themselves — only what is inside them
    /// (the profile, AppData, Documents…). Exact matches from the drive
    /// root; `?` = any one segment, a trailing `*` = prefix.
    /// </summary>
    private static readonly string[][] Containers = new[]
    {
        "users", "users/?", "users/public", "program files", "program files (x86)", "programdata",
        "users/?/appdata", "users/?/appdata/local", "users/?/appdata/roaming", "users/?/appdata/locallow",
        "users/?/appdata/local/packages", "users/?/appdata/local/programs",
        "users/?/documents", "users/?/desktop", "users/?/downloads", "users/?/pictures",
        "users/?/videos", "users/?/music", "users/?/favorites", "users/?/contacts", "users/?/links",
        "users/?/searches", "users/?/saved games", "users/?/3d objects", "users/?/onedrive*",
        "users/?/onedrive*/documents", "users/?/onedrive*/desktop", "users/?/onedrive*/pictures",
    }.Select(Split).ToArray();

    /// <summary>True for a folder that may only be cleaned inside, never as a whole (see <see cref="Containers"/>).</summary>
    public static bool IsContainer(string fullPath)
    {
        var segs = Segments(fullPath);
        foreach (var pattern in Containers)
        {
            if (segs.Length != pattern.Length + 1) continue;
            bool ok = true;
            for (int k = 0; k < pattern.Length && ok; k++)
                ok = SegmentMatches(pattern[k], segs[k + 1]);
            if (ok) return true;
        }
        return false;
    }

    /// <summary>Lower-cased path segments: "C:\Users\me" → ["c:", "users", "me"].</summary>
    private static string[] Segments(string path) =>
        path.ToLowerInvariant().Split(['\\', '/'], StringSplitOptions.RemoveEmptyEntries);

    /// <summary>
    /// The first folder rule whose pattern ends at <paramref name="count"/>
    /// segments of <paramref name="segs"/>; null when none does.
    /// </summary>
    private static Rule? MatchFolder(string[] segs, int count)
    {
        foreach (var rule in FolderRules)
        {
            int start = count - rule.Pattern.Length;
            if (start < 1) continue;   // never match the drive itself
            if (rule.AnchorDepth >= 0 && start != rule.AnchorDepth) continue;
            bool ok = true;
            for (int k = 0; k < rule.Pattern.Length && ok; k++)
                ok = SegmentMatches(rule.Pattern[k], segs[start + k]);
            if (ok) return rule;
        }
        return null;
    }

    private static bool SegmentMatches(string pattern, string segment)
    {
        if (pattern == "?") return true;
        if (pattern.Length > 2 && pattern[0] == '*' && pattern[^1] == '*')
            return segment.Contains(pattern[1..^1], StringComparison.Ordinal);
        if (pattern[^1] == '*') return segment.StartsWith(pattern[..^1], StringComparison.Ordinal);
        return segment == pattern;
    }

    private static StorageVerdict? FileVerdict(string name)
    {
        if (FileNames.TryGetValue(name, out var byName)) return byName;
        int dot = name.LastIndexOf('.');
        return dot > 0 && Extensions.TryGetValue(name[dot..], out var byExt) ? byExt : null;
    }

    /// <summary>
    /// Classifies one path: the first claim rule along its folders wins;
    /// otherwise a file rule; otherwise the innermost area; otherwise Other.
    /// A claim's advice covers everything inside it (ext4.vhdx under
    /// AppData\Local\wsl is a WSL distro, not just "a disk image").
    /// </summary>
    public static StorageVerdict Classify(string fullPath, bool isDirectory)
    {
        var verdict = ClassifyPath(fullPath, isDirectory);
        return isDirectory && IsContainer(fullPath)
            ? verdict with { Advice = CleanupAdvice.Never, Note = ContainerNote, Instead = null }
            : verdict;
    }

    private static StorageVerdict ClassifyPath(string fullPath, bool isDirectory)
    {
        var segs = Segments(fullPath);
        StorageVerdict? area = null;
        int folderCount = isDirectory ? segs.Length : segs.Length - 1;
        for (int count = 2; count <= folderCount; count++)
        {
            if (MatchFolder(segs, count) is not { } rule) continue;
            var verdict = new StorageVerdict(rule.Class, rule.Advice, rule.Note, rule.Instead);
            if (rule.Claim) return InstalledToolOrSelf(verdict, segs.AsSpan(0, count));
            area = verdict;
        }
        if (!isDirectory && segs.Length > 0 && FileVerdict(segs[^1]) is { } file) return file;
        return area ?? new StorageVerdict(Other, CleanupAdvice.Fine);
    }

    /// <summary>
    /// A node_modules/.venv/build output under plain AppData belongs to an
    /// installed tool (an agent, an Electron app's sources), not a project
    /// — removing it breaks the tool. Temp and known caches are claims of
    /// their own, so they never reach here.
    /// </summary>
    private static StorageVerdict InstalledToolOrSelf(StorageVerdict claim, ReadOnlySpan<string> folders) =>
        claim.Class == Dependencies && UnderAppData(folders)
            ? new StorageVerdict(AppData, CleanupAdvice.Warn, ToolNote, ToolInstead)
            : claim;

    private static bool UnderAppData(ReadOnlySpan<string> folders)
    {
        foreach (var s in folders) if (s == "appdata") return true;
        return false;
    }

    /// <summary>Bytes per class plus the biggest node each class claimed (for drill-in).</summary>
    public sealed record ClassTotal(StorageClass Class, long Bytes, int? LargestNode);

    /// <summary>
    /// Exclusive rollup of the whole tree into classes: claims take whole
    /// subtrees, files fall to their file rule or the innermost area.
    /// Sums to <c>totals[0]</c>. O(nodes); run it off the UI thread.
    /// </summary>
    public static List<ClassTotal> Rollup(FileTree tree, string rootPath, long[] totals)
    {
        if (tree.Count == 0) return [];
        var bytes = new Dictionary<StorageClass, long>();
        var largest = new Dictionary<StorageClass, (int Node, long Bytes)>();
        void Add(StorageClass c, int node, long size)
        {
            if (size <= 0) return;
            bytes[c] = bytes.GetValueOrDefault(c) + size;
            if (!largest.TryGetValue(c, out var l) || size > l.Bytes) largest[c] = (node, size);
        }

        var rootSegs = Segments(rootPath);
        // The root itself may sit inside a claim or an area (scanning
        // C:\Users\me\AppData\Local\wsl directly).
        StorageClass? rootArea = null;
        for (int count = 2; count <= rootSegs.Length; count++)
        {
            if (MatchFolder(rootSegs, count) is not { } rule) continue;
            if (rule.Claim) return [new ClassTotal(rule.Class, totals[0], 0)];
            rootArea = rule.Class;
        }

        // Depth-first with one shared segment buffer: a frame re-writes its
        // own segment when popped, and everything below it is written by
        // its descendants before any sibling pops — so the buffer always
        // holds the popped folder's full path.
        var segs = new string[rootSegs.Length + 512];
        Array.Copy(rootSegs, segs, rootSegs.Length);
        var stack = new Stack<(int Node, int Depth, StorageClass? Area)>();
        stack.Push((0, rootSegs.Length, rootArea));
        while (stack.TryPop(out var frame))
        {
            if (frame.Node != 0) segs[frame.Depth - 1] = tree.NameOf(frame.Node).ToLowerInvariant();
            for (int c = tree.FirstChild[frame.Node]; c != -1; c = tree.NextSibling[c])
            {
                long size = totals[c];
                if (size <= 0) continue;
                if (!tree.IsDirectory[c])
                {
                    Add(FileVerdict(tree.NameOf(c))?.Class ?? frame.Area ?? Other, c, size);
                    continue;
                }
                if (frame.Depth >= segs.Length) { Add(frame.Area ?? Other, c, size); continue; }
                segs[frame.Depth] = tree.NameOf(c).ToLowerInvariant();
                var rule = MatchFolder(segs, frame.Depth + 1);
                if (rule is { Claim: true })
                {
                    // Same exception as Classify: dependencies inside AppData are the tool's.
                    Add(rule.Class == Dependencies && UnderAppData(segs.AsSpan(0, frame.Depth + 1)) ? AppData : rule.Class, c, size);
                    continue;
                }
                stack.Push((c, frame.Depth + 1, rule?.Class ?? frame.Area));
            }
        }
        return All.Where(bytes.ContainsKey)
            .Select(c => new ClassTotal(c, bytes[c], largest.TryGetValue(c, out var l) ? l.Node : null))
            .OrderByDescending(t => t.Class == Other ? -1 : t.Bytes)
            .ToList();
    }
