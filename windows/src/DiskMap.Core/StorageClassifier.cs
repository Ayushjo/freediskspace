    private sealed record Rule(
        string[] Pattern, StorageClass Class, bool Claim,
        CleanupAdvice Advice = CleanupAdvice.Fine, string? Note = null, string? Instead = null,
        int AnchorDepth = -1);

    private static Rule Claim(string pattern, StorageClass c, CleanupAdvice a = CleanupAdvice.Fine,
        string? note = null, string? instead = null, int depth = -1) =>
        new(Split(pattern), c, true, a, note, instead, depth);

    private static Rule Area(string pattern, StorageClass c, CleanupAdvice a = CleanupAdvice.Fine,
        string? note = null, string? instead = null, int depth = -1) =>
        new(Split(pattern), c, false, a, note, instead, depth);

    private static string[] Split(string pattern) =>
        pattern.ToLowerInvariant().Split('/', StringSplitOptions.RemoveEmptyEntries);

