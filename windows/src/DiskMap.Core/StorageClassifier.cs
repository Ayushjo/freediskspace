    public static StorageClass ById(string id) => All.FirstOrDefault(c => c.Id == id) ?? Other;

    /// <summary>
    /// The Recycle Bin and restore-point store: what's in there was already
    /// thrown away or belongs to Windows — never a finding (a node_modules
    /// sitting in the bin is not developer storage to clean).
    /// </summary>
    public static bool IsSystemHolding(string path) =>
        path.Contains(@"\$Recycle.Bin", StringComparison.OrdinalIgnoreCase)
        || path.Contains(@"\System Volume Information", StringComparison.OrdinalIgnoreCase);

    /// <summary>True for the classes a developer owns — the Developer Storage family.</summary>
    public static bool IsDeveloper(StorageClass c) =>
        c == Projects || c == Dependencies || c == DevTools || c == PackageCaches || c == VirtualDisks || c == AiModels;

